"""One customer-stop QR over exact, independently reserved partial stock identities.

A pack is a custody/grouping document, never an ERP stock movement or a replacement
for a Quantity Bin, mixed Logistics Container or manufacturing WIP bin.
"""
import json
from contextlib import contextmanager

import frappe
from frappe.utils import flt, now_datetime

from cfg_kanban.services.events import record
from cfg_kanban.services.idempotency import canonical_key
from cfg_kanban.services.operator_auth import require_operator
from cfg_kanban.services.logistics_foundation import post_quantity_event, resolve_logistics_scan

PACK = 'CFG Kanban Loose Tag'
LINE = 'CFG Kanban Loose Tag Line'
HU = 'CFG Kanban Handling Unit'
PLAN = 'CFG Kanban Dispatch Plan'
TRIP = 'CFG Kanban Delivery Trip'
PREFIX = 'CFG:LOOSE:'
EPS = 0.000001


def _planning():
    from cfg_kanban.services import dispatch_planning
    return dispatch_planning


def _identity():
    from cfg_kanban.services import logistics_stock_identity
    return logistics_stock_identity


@contextmanager
def _atomic():
    point = 'loose_tag_' + frappe.generate_hash(length=10)
    frappe.db.savepoint(point)
    try:
        yield
    except Exception:
        try:
            frappe.db.rollback(save_point=point)
        except Exception:
            frappe.db.rollback()
        raise


def is_loose_tag(value):
    return str(value or '').strip().startswith(PREFIX)


def _name(scan):
    value = str(scan or '').strip()
    return value[len(PREFIX):] if value.startswith(PREFIX) else value


def _pack(scan, current=False):
    doc = frappe.get_doc(PACK, _name(scan), **({'for_update': True} if current else {}))
    doc.check_permission('read')
    return doc


def _lock_request_plan(name, operator):
    candidate = frappe.get_doc(PLAN, name)
    candidate.check_permission('read')
    if not candidate.get('office_delivery_trip'):
        frappe.throw('Select a Dispatch Plan generated by an office Delivery Trip')
    trip = frappe.get_doc(TRIP, candidate.office_delivery_trip, for_update=True)
    trip.check_permission('read')
    plan = _planning()._locked_authorized_plan(name, operator)
    frappe.get_doc('Company', plan.company).check_permission('read')
    if plan.office_delivery_trip != trip.name:
        frappe.throw('Dispatch Plan Trip changed; refresh before continuing')
    return plan


def _scope(name, operator, warehouse=False, stop_key=None, choose=False):
    candidate = frappe.get_doc(PLAN, name)
    candidate.check_permission('read')
    if not candidate.get('office_delivery_trip'):
        frappe.throw('Select a customer Dispatch Plan generated by an office Delivery Trip')
    trip = frappe.get_doc(TRIP, candidate.office_delivery_trip, for_update=True)
    trip.check_permission('read')
    plan = _planning()._locked_authorized_plan(name, operator)
    if plan.office_delivery_trip != trip.name:
        frappe.throw('Dispatch Plan Trip changed; refresh before packing')
    shared = plan.plan_type == 'Open Route Stock' and trip.get('open_route_plan') == plan.name
    target = stop_key if shared else plan.get('office_stop_key')
    if not shared and stop_key and stop_key != target:
        frappe.throw('Select the exact customer stop assigned to this Dispatch Plan')
    stop = next((r for r in trip.stops if r.stop_key == target), None)
    if (trip.state not in ('Draft','Planned') or plan.fulfilment_mode != 'Vehicle Delivery'
            or plan.company != trip.company or plan.get('stop_cancellation')):
        frappe.throw('Loose Tags require an active office Trip / Vehicle Delivery Plan')
    if shared and choose and not target:
        stop = None
    elif (not stop or stop.get('cancellation_request')
            or (shared and stop.stop_purpose != 'Visit Only')
            or (not shared and (stop.stop_purpose != 'Delivery' or plan.plan_type != 'Customer Order'
                or plan.customer != stop.customer or plan.customer_site != stop.customer_scan_point
                or plan.name not in {r.dispatch_plan for r in trip.dispatch_plans if r.stop_key == stop.stop_key}))):
        frappe.throw('Select the exact active customer stop for this customer Plan or shared Open Route pool')
    frappe.get_doc('Company', plan.company).check_permission('read')
    frappe.get_doc('Warehouse', plan.source_warehouse).check_permission('read')
    if warehouse:
        from cfg_kanban.services.container_contents import _authorize
        _authorize(warehouse, write=True)
        if trip.get('driver_route_state') not in (None, '', 'Not Started') or plan.movement_manifest or plan.vehicle_warehouse or plan.delivery_session:
            frappe.throw('Correct unused Loose Tags before vehicle claim; loaded goods use Dispatch Recovery')
        _planning()._assert_reservable(plan, 'Tagged')
    return trip, stop, plan


def _source(scan):
    identity = resolve_logistics_scan(scan)
    if not identity or identity.get('identity_type') != 'Handling Unit':
        frappe.throw('Scan an active source Stock Tag')
    unit = frappe.get_doc(HU, identity['name'])
    unit.check_permission('read')
    if unit.get('loose_tag'):
        frappe.throw('Loose Tag contents cannot be packed again; cancel the unused pack or recover its remaining stock')
    return unit


def _source_ready(unit, plan, line, qty):
    from cfg_kanban.services.logistics_quantity_bins import _validate_source
    from cfg_kanban.services.dispatch_fulfilment import assert_prepared_tag_scope, assert_delivery_tag_expiry
    _validate_source(frappe._dict(inventory_company=plan.company, current_warehouse=plan.source_warehouse), unit, qty)
    _planning()._validate_tag_for_plan(unit, plan, line)
    assert_prepared_tag_scope(unit.name, frappe._dict(dispatch_plan=None), current=True)
    assert_delivery_tag_expiry(unit)
    if not frappe.db.get_value('Item',unit.item_code,'is_stock_item'):
        frappe.throw('Loose Tags require Items that maintain ERPNext stock')
    if frappe.db.get_value('Item', unit.item_code, 'has_serial_no'):
        frappe.throw('Loose Tags currently require non-serialized stock; use the existing exact-serial tag workflow')
    _planning().assert_erp_stock(unit, plan.source_warehouse, qty)


@frappe.whitelist()
def packing_context(dispatch_plan, operator_session_token, source_scan=None, stop_key=None):
    operator, _session = require_operator(operator_session_token, 'start')
    trip, stop, plan = _scope(dispatch_plan, operator, operator_session_token, stop_key, choose=True)
    if not stop:
        return dict(dispatch_plan=plan.name, delivery_trip=trip.name, stops=[dict(stop_key=r.stop_key,
            customer=r.customer, site_name=r.site_name or r.customer) for r in trip.stops
            if r.stop_purpose == 'Visit Only' and not r.get('cancellation_request')])
    _planning()._current_reservation_lines(plan)
    rows = []
    unit = _source(source_scan) if source_scan else None
    for line in plan.lines:
        if unit and (unit.item_code != line.item_code or unit.stock_uom != line.stock_uom
                     or line.batch_no and unit.batch_no != line.batch_no):
            continue
        remaining = max(0, flt(line.requested_qty) - _planning()._active_line_reserved(line.name, current=True))
        if remaining > EPS:
            rows.append(dict(name=line.name, item_code=line.item_code, batch_no=line.batch_no,
                stock_uom=line.stock_uom, remaining_qty=remaining, sales_order_item=line.get('sales_order_item')))
    if unit and not rows:
        frappe.throw('This source has no matching unreserved Item / Batch / UOM in the selected Plan')
    if unit:
        if flt(unit.available_qty) <= EPS:
            frappe.throw('The scanned source has no available stock')
        _source_ready(unit, plan, next(r for r in plan.lines if r.name == rows[0]['name']), min(flt(unit.available_qty), 1))
    return dict(dispatch_plan=plan.name, delivery_trip=trip.name, stop_key=stop.stop_key,
        customer=stop.customer, site_name=stop.site_name or stop.customer, lines=rows,
        source=dict(name=unit.name, scan=source_scan, visible_code=unit.handling_unit_id,
            item_code=unit.item_code, batch_no=unit.batch_no, stock_uom=unit.stock_uom,
            available_qty=unit.available_qty) if unit else None)


def _request(lines):
    rows = frappe.parse_json(lines) if isinstance(lines, str) else lines
    if not isinstance(rows, list) or not rows or len(rows) > 100:
        frappe.throw('Pack between one and 100 source lines')
    result = []
    for row in rows:
        if not isinstance(row, dict) or set(row) != {'dispatch_plan_line', 'source_scan', 'qty'}:
            frappe.throw('Each packed line requires its Plan row, scanned source and stock quantity')
        qty = _planning()._reservation_qty(row['qty'])
        if qty <= EPS:
            frappe.throw('Packed quantity must be positive')
        result.append(dict(dispatch_plan_line=str(row['dispatch_plan_line']), source_scan=str(row['source_scan']).strip(), qty=qty))
    return result


@frappe.whitelist(methods=['POST'])
def create_loose_tag(dispatch_plan, lines, event_token, operator_session_token, stop_key=None):
    operator, session = require_operator(operator_session_token, 'start')
    _planning()._require_event_token(event_token)
    submitted = _request(lines)
    # Scope and authorization precede replay; mutable picking gates follow replay.
    plan = _lock_request_plan(dispatch_plan, operator)
    key = canonical_key('loose-tag-create', operator.employee, event_token)
    existing = frappe.db.get_value(PACK, {'creation_key': key}, 'name', for_update=True)
    if existing:
        doc = _pack(existing, True)
        fingerprint = canonical_key('loose-tag-request',dispatch_plan,stop_key or plan.get('office_stop_key') or doc.stop_key,submitted)
        if doc.request_hash != fingerprint or doc.dispatch_plan != plan.name:
            frappe.throw('This Loose Tag request token already describes different packed contents')
        return _result(doc)
    trip, stop, plan = _scope(dispatch_plan, operator, operator_session_token, stop_key)
    fingerprint = canonical_key('loose-tag-request', dispatch_plan, stop.stop_key, submitted)
    _planning()._current_reservation_lines(plan)
    sources = [_source(row['source_scan']) for row in submitted]
    if len({u.name for u in sources}) != len(sources):
        frappe.throw('Scan each source Stock Tag only once per pack; combine its packed quantity')
    for item in sorted({u.item_code for u in sources}):
        _planning()._lock_erp_bin(item, plan.source_warehouse)
    sources = {name: frappe.get_doc(HU, name, for_update=True) for name in sorted({u.name for u in sources})}
    prepared = []
    budgets = {}
    for raw in submitted:
        line = _planning()._plan_line(plan, raw['dispatch_plan_line'])
        unit = sources[_source(raw['source_scan']).name]
        _planning()._reservation_uom(raw['qty'], unit.stock_uom)
        _source_ready(unit, plan, line, raw['qty'])
        budgets[line.name] = budgets.get(line.name, 0) + raw['qty']
        if budgets[line.name] > flt(line.requested_qty) - _planning()._active_line_reserved(line.name, current=True) + EPS:
            frappe.throw('Packed quantities exceed the remaining Dispatch Plan request')
        prepared.append(dict(dispatch_plan_line=line.name, source_handling_unit=unit.name,
            source_visible_code=unit.handling_unit_id, item_code=unit.item_code, batch_no=unit.batch_no,
            stock_uom=unit.stock_uom, qty=raw['qty'], expiry_date=_identity()._expiry(_identity().identity_snapshot(unit)) or unit.expiry_date,
            process_certificate_set=unit.get('process_certificate_set')))
    with _atomic():
        doc = frappe.get_doc(dict(doctype=PACK, state='Building', delivery_trip=trip.name,
            stop_key=stop.stop_key, dispatch_plan=plan.name, company=plan.company, customer=stop.customer,
            customer_site=stop.customer_scan_point, source_warehouse=plan.source_warehouse, created_on=now_datetime(),
            packed_by=operator.employee, operator_session=session.name, creation_key=key, request_hash=fingerprint, lines=prepared))
        doc.flags.cfg_loose_tag_controlled = True
        doc.insert(ignore_permissions=True)
        if resolve_logistics_scan(PREFIX + doc.name):
            frappe.throw('Loose Tag QR conflicts with an existing physical identity; resolve that identity before packing')
        for row in doc.lines:
            source = sources[row.source_handling_unit]
            fill = _new_fill(doc, row, source)
            ledger = _move(source, fill, row.qty, 'Split', canonical_key('loose-tag-split', row.name), doc, operator, session)
            source.reload(); fill.reload()
            _identity().inherit_split_certificates(source, fill, row.qty, key)
            if flt(source.current_qty) <= EPS:
                source.db_set(dict(identity_state='Empty', movement_state='Empty'), update_modified=False)
            _planning().reserve_dispatch_tag(plan.name, row.dispatch_plan_line, fill.handling_unit_id,
                row.qty, canonical_key('loose-tag-reserve', row.name), operator_session_token)
            allocation = frappe.db.get_value('CFG Kanban Dispatch Allocation', {'active_handling_unit_key':fill.name}, 'name', for_update=True)
            if not allocation:
                frappe.throw('The packed line has no confirmed Dispatch reservation')
            row.db_set(dict(handling_unit=fill.name, dispatch_allocation=allocation, split_ledger=ledger.name), update_modified=False)
        doc.db_set(dict(state='Ready', qr_payload=PREFIX + doc.name), update_modified=True)
        plan.db_set('has_loose_tags', 1, update_modified=False)
        _audit(doc, 'Loose Tag Packed', operator, session, key)
        doc.reload()
        return _result(doc)


def _new_fill(doc, row, source):
    fill = frappe.copy_doc(source)
    fill.update(dict(name=None, handling_unit_id='LOOSE-LINE-' + canonical_key('loose-line', row.name)[:24].upper(),
        opaque_token=None, tag_kind='Main Stock Tag', tag_family=None, tag_range_registry=None,
        parent_handling_unit=None, root_handling_unit=None, child_index=0, virtual_content=0,
        physical_container=None, loose_tag=doc.name, loose_tag_line=row.name,
        qty=row.qty, original_qty=row.qty, current_qty=0, reserved_qty=0, available_qty=0,
        activation_key=canonical_key('loose-fill', row.name), state='Attached', identity_state='Active',
        movement_state='Packed', replacement_of=None, replaced_by=None, void_reason=None,
        print_count=0, print_revision=1, last_printed_on=None, last_printed_by=None, last_scan_time=None,
        origin_reference_doctype=HU, origin_reference_name=source.name, origin_reference_row=row.name))
    old = frappe.flags.get('cfg_creating_loose_tag')
    frappe.flags.cfg_creating_loose_tag = doc.name
    try:
        fill.flags.skip_initial_ledger = True
        fill.insert(ignore_permissions=True)
    finally:
        frappe.flags.cfg_creating_loose_tag = old
    return fill


def validate_internal_fill(unit):
    if frappe.flags.get('cfg_creating_loose_tag') != unit.loose_tag:
        frappe.throw('Internal Loose Tag stock is created only by controlled packing')
    pack = _pack(unit.loose_tag)
    row = next((r for r in pack.lines if r.name == unit.loose_tag_line), None)
    if (pack.state != 'Building' or not row or unit.tag_kind != 'Main Stock Tag'
            or unit.virtual_content or unit.physical_container or unit.tag_family or unit.tag_range_registry
            or unit.parent_handling_unit or unit.inventory_company != pack.company
            or unit.current_warehouse != pack.source_warehouse or unit.origin_reference_name != row.source_handling_unit
            or any((unit.get(f) or '') != (row.get(f) or '') for f in ('item_code','batch_no','stock_uom'))
            or abs(flt(unit.qty)-flt(row.qty)) > EPS):
        frappe.throw('Internal Loose Tag stock must match its exact controlled packed line')


def _move(source, target, qty, kind, key, doc, operator, session):
    return post_quantity_event(event_type=kind, qty=qty, stock_uom=source.stock_uom,
        idempotency_key=key, source_handling_unit=source.name, destination_handling_unit=target.name,
        item_code=source.item_code, batch_no=source.batch_no,
        source_company=source.inventory_company, destination_company=target.inventory_company,
        source_warehouse=source.current_warehouse, destination_warehouse=target.current_warehouse,
        reference_doctype=PACK, reference_name=doc.name, operator=operator.employee,
        operator_session=session.name, reason='Controlled customer-stop Loose Tag ' + kind)


def _audit(doc, action, operator, session, key, reason=None):
    record(action, reference_doctype=PACK, reference_name=doc.name, operator=operator.employee,
        operator_session=session.name, terminal_user=session.terminal_user, idempotency_key=key, notes=reason)


def _result(doc):
    result = doc.as_dict()
    for row in result['lines']:
        if row.get('handling_unit'):
            unit = frappe.get_doc(HU, row['handling_unit'])
            row['remaining_qty'] = unit.current_qty
            row['current_warehouse'] = unit.current_warehouse
    return result


@frappe.whitelist()
def get_loose_tag(scan_value, operator_session_token):
    operator, _session = require_operator(operator_session_token)
    doc = _pack(scan_value)
    _planning()._assert_plan_authorized(frappe.get_doc(PLAN, doc.dispatch_plan), operator)
    frappe.get_doc('Company', doc.company).check_permission('read')
    return _result(doc)


@frappe.whitelist(methods=['POST'])
def cancel_loose_tag(scan_value, reason, event_token, operator_session_token):
    operator, session = require_operator(operator_session_token, 'start')
    _planning()._require_event_token(event_token)
    reason = str(reason or '').strip()
    if not reason:
        frappe.throw('A cancellation reason is required')
    candidate = _pack(scan_value)
    plan = _lock_request_plan(candidate.dispatch_plan, operator)
    doc = _pack(candidate.name, True)
    key = canonical_key('loose-tag-cancel', operator.employee, event_token)
    if doc.state == 'Cancelled':
        if doc.cancel_key == key and doc.cancel_reason != reason:
            frappe.throw('This cancellation token already describes a different reason')
        return _result(doc)
    _scope(plan.name, operator, operator_session_token, doc.stop_key)
    with _atomic():
        _undo(doc, plan, operator, session, reason, key)
        _planning()._refresh_plan_totals(plan.name)
        return _result(doc)


def _undo(doc, plan, operator, session, reason, key):
    if doc.state != 'Ready' or plan.movement_manifest or plan.delivery_session or plan.vehicle_warehouse:
        frappe.throw('Only an unused unclaimed Loose Tag can be undone; use Dispatch Recovery for loaded goods')
    for item in sorted({r.item_code for r in doc.lines}):
        _planning()._lock_erp_bin(item, plan.source_warehouse)
    units = {name:frappe.get_doc(HU, name, for_update=True)
             for name in sorted({r.handling_unit for r in doc.lines} | {r.source_handling_unit for r in doc.lines})}
    for row in doc.lines:
        source, fill = units[row.source_handling_unit], units[row.handling_unit]
        allocation = frappe.get_doc('CFG Kanban Dispatch Allocation', row.dispatch_allocation, for_update=True)
        if (allocation.dispatch_plan != plan.name or allocation.handling_unit != fill.name
                or allocation.state not in ('Reserved','Released','Cancelled')
                or abs(flt(fill.current_qty)-flt(row.qty)) > EPS):
            frappe.throw('Packed stock changed; reconcile it through Dispatch Recovery')
        # The original tag may have since moved or been reused; never merge across identities/warehouses.
        _identity().assert_merge_compatible(fill, source)
        from cfg_kanban.services.container_contents import active_container_membership
        from cfg_kanban.services.logistics_quantity_bins import _assert_source_not_in_open_transaction
        if active_container_membership(source.name):
            frappe.throw('Unload the original source from its container before unpacking')
        _assert_source_not_in_open_transaction(source.name)
        if flt(source.reserved_qty) > EPS:
            frappe.throw('Original source is reserved by another transaction; release that reservation before unpacking')
        if (source.current_warehouse != fill.current_warehouse or source.inventory_company != fill.inventory_company
                or fill.current_warehouse != doc.source_warehouse or source.identity_state not in ('Active','Empty')):
            frappe.throw('Original source changed location/state; restore it before unpacking')
        _planning()._release_allocation(allocation, plan, operator, session, reason, key)
        fill.reload()
        if flt(fill.reserved_qty) > EPS:
            frappe.throw('Packed stock has another reservation; reconcile before unpacking')
        _move(fill, source, row.qty, 'Merge', canonical_key('loose-tag-unpack', row.name), doc, operator, session)
        source.reload(); fill.reload()
        _identity().inherit_split_certificates(fill, source, row.qty, key)
        source.db_set(dict(identity_state='Active', movement_state='Received'), update_modified=False)
        fill.db_set(dict(identity_state='Empty', movement_state='Empty'), update_modified=False)
    doc.db_set(dict(state='Cancelled', cancel_reason=reason, cancel_key=key,
        cancelled_on=now_datetime(), cancelled_by=operator.employee), update_modified=True)
    _audit(doc, 'Loose Tag Cancelled', operator, session, key, reason)


def before_plan_cancel(plan, operator, session, reason, event_token):
    for name in frappe.get_all(PACK, filters={'dispatch_plan':plan.name, 'state':['!=','Cancelled']}, pluck='name', limit_page_length=0):
        _undo(_pack(name, True), plan, operator, session, reason, canonical_key('loose-tag-plan-cancel', name, event_token))


def guard_release(allocation, plan):
    name = frappe.db.get_value(HU, allocation.handling_unit, 'loose_tag') if allocation.handling_unit else None
    if name and _pack(name).state != 'Cancelled':
        frappe.throw('Cancel the unused Loose Tag to release and unpack all its lines together')


def packs_for_plan(plan, stop_key=None):
    return [frappe.get_doc(PACK, r.name) for r in frappe.get_all(PACK,
        filters={'dispatch_plan':plan.name,'state':['!=','Cancelled'], **({'stop_key':stop_key} if stop_key else {})}, fields=['name'], order_by='creation asc', limit_page_length=0)]


def _validate_lines(doc, plan, state='Loaded'):
    if doc.state in ('Cancelled','Processed','In Delivery'):
        frappe.throw('This Loose Tag has already been processed or cancelled; view its recorded result')
    if doc.dispatch_plan != plan.name or doc.company != plan.company or (plan.plan_type == 'Customer Order' and doc.customer != plan.customer):
        frappe.throw('Loose Tag customer / Plan scope changed')
    for row in doc.lines:
        allocation = frappe.get_doc('CFG Kanban Dispatch Allocation', row.dispatch_allocation, for_update=True)
        unit = frappe.get_doc(HU, row.handling_unit, for_update=True)
        if (allocation.dispatch_plan != plan.name or allocation.handling_unit != unit.name
                or allocation.dispatch_plan_line != row.dispatch_plan_line or allocation.state != state
                or abs(flt(allocation.allocated_qty)-flt(row.qty)) > EPS
                or unit.loose_tag != doc.name or unit.loose_tag_line != row.name
                or any((unit.get(f) or '') != (row.get(f) or '') for f in ('item_code','batch_no','stock_uom'))
                or abs(flt(unit.current_qty)-flt(row.qty)) > EPS):
            frappe.throw('Loose Tag source identity, reservation or quantity changed; request supervised reconciliation')
        if state == 'Loaded' and (not allocation.load_confirmed or unit.current_warehouse != plan.vehicle_warehouse
                                  or unit.inventory_company != doc.company):
            frappe.throw('Every Loose Tag line must be loaded on the assigned lorry')


@frappe.whitelist(methods=['POST'])
def scan_loose_tag(trip_name, stop_key, scan_value, operator_session_token):
    """Arrival acknowledgement only: native delivery remains the sole consumption path."""
    from cfg_kanban.services import driver_route_actions as actions
    operator, session = require_operator(operator_session_token, 'start')
    trip = actions._root(trip_name)
    actions._owned(trip, operator)
    saved = json.loads(trip.driver_route_snapshot_json or '{}')
    stop = actions._target(trip, dict(stop_key=stop_key), saved)
    doc = _pack(scan_value)
    if doc.delivery_trip != trip.name or doc.stop_key != stop.stop_key or doc.customer != stop.customer:
        frappe.throw('This Loose Tag belongs to another customer stop')
    _trip, _stop, plan = _scope(doc.dispatch_plan, operator, stop_key=doc.stop_key)
    doc = _pack(doc.name, True)
    if plan.get('dispatch_review_state') or plan.get('stop_cancellation') or (plan.plan_type == 'Customer Order' and plan.delivery_session):
        frappe.throw('This delivery was already started or frozen; view its existing result')
    _validate_lines(doc, plan)
    if plan.plan_type == 'Open Route Stock':
        from cfg_kanban.services.trip_sales import visit
        native = visit(trip, stop, current=True)
        if not native or native.delivery_session:
            frappe.throw('This optional sale already has a Session; resume its recorded pack outcome')
    if doc.state == 'Ready':
        doc.db_set(dict(state='Scanned', scanned_on=now_datetime(), scanned_by=operator.employee), update_modified=True)
        _audit(doc, 'Loose Tag Scanned at Customer Stop', operator, session, canonical_key('loose-tag-arrival', doc.name))
    return _result(doc)


def assert_scanned(plan, stop_key=None):
    for pack in packs_for_plan(plan, stop_key):
        pack = _pack(pack.name, True)
        _validate_lines(pack, plan)
        if pack.state != 'Scanned' or not pack.scanned_on:
            frappe.throw('Scan every assigned Loose Tag at its customer stop before confirming delivery')


def bind_delivery(plan, delivery, stop_key=None):
    for pack in packs_for_plan(plan, stop_key):
        pack.db_set(dict(state='In Delivery', delivery_session=delivery.name), update_modified=True)


def sync_delivery(delivery):
    if not delivery.get('dispatch_plan'):
        return
    for pack in packs_for_plan(frappe._dict(name=delivery.dispatch_plan)):
        if pack.delivery_session != delivery.name:
            continue
        if delivery.state in ('Delivered','Closed','Invoiced'):
            pack.db_set(dict(state='Processed', delivery_note=delivery.delivery_note), update_modified=True)
        elif delivery.state in ('Cancelled','Exception'):
            pack.db_set('state', 'Recovery Required', update_modified=True)


def driver_context(plan, stop_key=None):
    return [dict(name=p.name, qr_payload=p.qr_payload, state=p.state,
        lines=[dict(dispatch_allocation=r.dispatch_allocation,item_code=r.item_code,batch_no=r.batch_no,
                    stock_uom=r.stock_uom,qty=r.qty,source_visible_code=r.source_visible_code) for r in p.lines]) for p in packs_for_plan(plan, stop_key)]


def stock_codes(scan_value):
    """Remaining stock behind one QR for existing counts and leftover recovery scans."""
    doc = _pack(scan_value)
    if doc.state in ('Cancelled','Building'):
        frappe.throw('This Loose Tag is cancelled or unfinished')
    codes = []
    for row in doc.lines:
        unit = frappe.get_doc(HU, row.handling_unit)
        unit.check_permission('read')
        if flt(unit.current_qty) > EPS:
            codes.append(unit.handling_unit_id)
    if not codes:
        frappe.throw('This Loose Tag has no remaining stock')
    return codes


def scan_group(scan_value, callback):
    with _atomic():
        result = None
        for code in stock_codes(scan_value):
            result = callback(code)
        return result


def open_context(plan, stop_key):
    packs = driver_context(plan, stop_key)
    if not packs:
        return {}
    names = {r['dispatch_allocation'] for p in packs for r in p['lines']}
    from cfg_kanban.services.dispatch_fulfilment import _loaded_allocations
    sources = [r for r in _loaded_allocations(plan) if r.name in names]
    if {r.name for r in sources} != names:
        frappe.throw('Every assigned Loose Tag must retain its exact loaded source allocation')
    return dict(loose_tags=packs, quantities=[dict(dispatch_allocation=r.name,
        source_label=' · '.join(filter(None,[r.item_code,r.batch_no,frappe.db.get_value(HU,r.handling_unit,'handling_unit_id')])),
        item_code=r.item_code,batch_no=r.batch_no,stock_uom=r.stock_uom,prepared_qty=r.allocated_qty,
        accepted_qty=r.allocated_qty,condition='Good / Unwanted',refusal_reason='') for r in sources])


def _open_quantities(plan, stop_key, submitted):
    from cfg_kanban.services.dispatch_fulfilment import _loaded_allocations
    from cfg_kanban.services.driver_delivery_outcomes import quantities
    packs = packs_for_plan(plan, stop_key)
    names = {r.dispatch_allocation for p in packs for r in p.lines}
    sources = [r for r in _loaded_allocations(plan) if r.name in names]
    if not sources or {r.name for r in sources} != names or submitted is None:
        frappe.throw('Review all exact assigned Loose Tag lines before confirming this sale')
    return quantities(plan, submitted, sources=sources)


