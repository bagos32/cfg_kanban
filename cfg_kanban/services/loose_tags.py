def begin_open_packs(trip, stop, plan, values, key, operator, session, token):
    from cfg_kanban.services.trip_sales import begin
    from cfg_kanban.services import route_delivery as route
    from cfg_kanban.services import driver_delivery_outcomes as outcomes
    packs = packs_for_plan(plan, stop.stop_key)
    if not packs:
        return begin(trip, stop, values.get('customer_scan'), key, operator, token)
    assert_scanned(plan, stop.stop_key)
    rows = _open_quantities(plan, stop.stop_key, values.get('quantities'))
    bad = [r for r in rows if r['refused_qty'] > EPS and r['condition'] != outcomes.SOUND]
    site = frappe.get_doc('CFG Kanban Customer Scan Point', stop.customer_scan_point)
    if bad:
        outcomes._returns()._assert_enabled(); outcomes._returns()._require_intake(operator)
        if not site.enable_customer_return_qc or not site.return_inspection_location:
            frappe.throw('Configure Customer Return QC and Inspection Custody Location for quality refusals')
    policy = json.loads(plan.profile_snapshot_json or '{}').get('sound_refusal_policy') or outcomes.HOLD
    if policy not in (outcomes.HOLD,outcomes.RELEASE):
        frappe.throw('Unsupported sound-refusal release policy')
    with _atomic():
        result = begin(trip, stop, values.get('customer_scan'), key, operator, token)
        delivery = frappe.get_doc('CFG Kanban Delivery Session', result['name'], for_update=True)
        if delivery.get('driver_delivery_outcome') or is_pack_delivery(delivery):
            frappe.throw('This Loose Tag sale was already processed; read back the original driver action')
        previous = frappe.flags.get('cfg_allocating_loose_open')
        frappe.flags.cfg_allocating_loose_open = delivery.name
        try:
            for row in rows:
                if row['accepted_qty'] <= EPS:
                    continue
                unit = frappe.get_doc(HU, row['handling_unit'], for_update=True)
                route.allocate_route_stock(delivery.name,row['dispatch_allocation'],row['accepted_qty'],
                    canonical_key('loose-open-allocate',key,row['dispatch_allocation']),token,scan_value=unit.handling_unit_id)
        finally:
            frappe.flags.cfg_allocating_loose_open = previous
        if any(r['refused_qty'] > EPS for r in rows):
            for row in rows:
                row['visible_code'] = next(r.source_visible_code for p in packs for r in p.lines
                                          if r.dispatch_allocation == row['dispatch_allocation'])
            outcome = frappe.get_doc(dict(doctype=outcomes.OUTCOME,state='Declared',delivery_trip=trip.name,
                stop_key=stop.stop_key,dispatch_plan=plan.name,
                active_plan_key=canonical_key('loose-open-outcome',plan.name,delivery.route_stop),company=plan.company,
                customer=stop.customer,customer_site=site.name,vehicle_warehouse=plan.vehicle_warehouse,
                sound_refusal_policy=policy,declared_on=now_datetime(),declared_by=operator.employee,
                operator_session=session.name,request_key=key,lines=rows))
            outcome.flags.cfg_controlled_outcome = True
            outcome.insert(ignore_permissions=True)
            outcomes.bind(outcome, delivery)
            outcomes.activate(outcome, delivery, operator, session)
        bind_delivery(plan, delivery, stop.stop_key)
        route.validate_route_allocations(delivery)
        route.sync_route_delivery(delivery)
        return route._engine().get_delivery_session(delivery.name, token)


def is_pack_delivery(delivery):
    return bool(frappe.db.get_value(PACK, {'delivery_session':delivery.name,'state':['!=','Cancelled']}, 'name'))


def assert_unit_scope(unit, delivery, validation=False):
    pack = _pack(unit.loose_tag)
    if pack.state in ('Cancelled','Recovery Required') or (pack.state == 'Processed' and not validation):
        frappe.throw('This Loose Tag has been processed; recover or retag its remaining stock before another sale')
    native = frappe.get_doc('CFG Kanban Route Stop', delivery.route_stop)
    if (pack.dispatch_plan != delivery.dispatch_plan or pack.delivery_trip != native.office_delivery_trip
            or pack.stop_key != native.office_stop_key or pack.customer != delivery.customer
            or pack.customer_site != delivery.customer_scan_point or pack.state not in ('Scanned','In Delivery','Processed')
            or pack.delivery_session and pack.delivery_session != delivery.name):
        frappe.throw('Loose Tag stock is reserved for another customer stop; scan its box at the assigned stop')
    if not pack.delivery_session and frappe.flags.get('cfg_allocating_loose_open') != delivery.name:
        frappe.throw('Confirm the complete Loose Tag from the driver stop screen; do not allocate its internal lines separately')


def validate_open_allocations(delivery, allocations):
    packs = [p for p in packs_for_plan(frappe._dict(name=delivery.dispatch_plan)) if p.delivery_session == delivery.name]
    for allocation in allocations:
        if allocation.handling_unit:
            unit = frappe.get_doc(HU,allocation.handling_unit)
            if unit.get('loose_tag'):
                assert_unit_scope(unit,delivery,validation=True)
    if not packs:
        if frappe.flags.get('cfg_allocating_loose_open') == delivery.name:
            return
        native = frappe.get_doc('CFG Kanban Route Stop',delivery.route_stop)
        if packs_for_plan(frappe._dict(name=delivery.dispatch_plan),native.office_stop_key):
            frappe.throw('Use the driver stop screen to confirm all assigned Loose Tag lines before creating the Delivery Note')
        return
    if delivery.get('driver_delivery_outcome'):
        from cfg_kanban.services.driver_delivery_outcomes import validate_allocations
        validate_allocations(delivery,allocations)
        return
    expected = {r.dispatch_allocation:r for p in packs for r in p.lines}
    if {r.dispatch_allocation for r in allocations} != set(expected) or len(allocations) != len(expected):
        frappe.throw('Every exact accepted Loose Tag line is required for this Delivery Note')
    for row in allocations:
        if abs(flt(row.allocated_qty)-flt(expected[row.dispatch_allocation].qty)) > EPS:
            frappe.throw('Loose Tag delivery quantities differ from its frozen acceptance')


@frappe.whitelist()
def read_packing_request(dispatch_plan, lines, event_token, operator_session_token, stop_key=None):
    operator, _session = require_operator(operator_session_token, 'start')
    plan = _lock_request_plan(dispatch_plan, operator)
    name = frappe.db.get_value(PACK, {'creation_key':canonical_key('loose-tag-create',operator.employee,event_token)}, 'name',for_update=True)
    if not name:
        return dict(recorded=False)
    doc = _pack(name,True)
    fingerprint = canonical_key('loose-tag-request',plan.name,stop_key or plan.get('office_stop_key') or doc.stop_key,_request(lines))
    if doc.request_hash != fingerprint:
        frappe.throw('This Loose Tag request token already describes different packed contents')
    return dict(recorded=True,pack=_result(doc))


@frappe.whitelist(methods=['POST'])
def void_packing_request(dispatch_plan, lines, event_token, reason, operator_session_token, stop_key=None):
    """Durable tombstone serializes with a late original packing request on the Trip lock."""
    operator, session = require_operator(operator_session_token, 'start')
    _planning()._require_event_token(event_token)
    reason = str(reason or '').strip()
    if not reason:
        frappe.throw('A reason is required before abandoning an unknown packing request')
    existing = read_packing_request(dispatch_plan,lines,event_token,operator_session_token,stop_key)
    if existing['recorded']:
        return existing['pack']
    trip, stop, plan = _scope(dispatch_plan,operator,operator_session_token,stop_key)
    doc = frappe.get_doc(dict(doctype=PACK,state='Cancelled',delivery_trip=trip.name,stop_key=stop.stop_key,
        dispatch_plan=plan.name,company=plan.company,customer=stop.customer,customer_site=stop.customer_scan_point,
        source_warehouse=plan.source_warehouse,created_on=now_datetime(),packed_by=operator.employee,
        creation_key=canonical_key('loose-tag-create',operator.employee,event_token),
        request_hash=canonical_key('loose-tag-request',plan.name,stop.stop_key,_request(lines)),lines=[],
        cancel_reason=reason,cancelled_on=now_datetime(),cancelled_by=operator.employee))
    doc.flags.cfg_loose_tag_controlled=True
    doc.insert(ignore_permissions=True)
    _audit(doc,'Unrecorded Loose Tag Request Voided',operator,session,doc.creation_key,reason)
    return _result(doc)


def project_open_sources(plan, stop_key, delivery=None):
    """Read-only per-stop pack and refusal visibility over the native pool allocations."""
    from cfg_kanban.services.driver_delivery_outcomes import refused_by_source
    refused = refused_by_source(delivery) if delivery and delivery.get('driver_delivery_outcome') else {}
    used = {}
    if delivery:
        for name in frappe.get_all('CFG Kanban Delivery Allocation', filters={'delivery_session':delivery.name,'state':'Delivered'},
                                   pluck='name', limit_page_length=0):
            row = frappe.get_doc('CFG Kanban Delivery Allocation',name);row.check_permission('read')
            used[row.dispatch_allocation] = used.get(row.dispatch_allocation,0) + flt(row.delivered_qty)
    result = []
    for pack in packs_for_plan(plan,stop_key):
        pack.check_permission('read')
        for row in pack.lines:
            allocation = frappe.get_doc('CFG Kanban Dispatch Allocation',row.dispatch_allocation)
            allocation.check_permission('read')
            held = refused.get(row.dispatch_allocation,{})
            loaded = flt(row.qty) if allocation.state in ('Loaded','In Fulfilment','Fulfilled') and allocation.load_confirmed else 0
            result.append(dict(dispatch_plan=plan.name,dispatch_allocation=row.dispatch_allocation,
                item_code=row.item_code,batch_no=row.batch_no,stock_uom=row.stock_uom,
                allocation_kind='Tagged Stock',tag_code=pack.qr_payload,original_source_tag=row.source_visible_code,
                assigned_qty=row.qty,loaded_qty=loaded,delivered_qty=used.get(row.dispatch_allocation,0),
                remaining_qty=max(0,loaded-used.get(row.dispatch_allocation,0)-flt(held.get('refused_qty'))),
                source_state=pack.state,refused_qty=flt(held.get('refused_qty')),refused_stock_state=held.get('stock_state'),
                refused_warehouse=held.get('current_warehouse'),qc_return_case=held.get('qc_return_case'),refusal_outcome=held.get('outcome')))
    return result


